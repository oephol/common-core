#include "libft.h"

int	ft_atoi(const char *nptr)
{
	size_t				i;
	int					sign;
	unsigned long		n;

	i = 0;
	while (nptr[i] == ' ' || (nptr[i] >= '\t' && nptr[i] <= '\r'))
		i++;
	sign = 1;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	n = 0;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		n = n * 10 + (nptr[i] - '0');
		if (n >= 9223372036854775807 && sign > 0)
			return (-1);
		else if (n > 9223372036854775807 && sign < 0)
			return (0);
		i++;
	}
	return (sign * n);
}
